fun fontFamilyForLanguage(languageCode: String): FontFamily {
    return if (languageCode.equals("ta", ignoreCase = true)) {
        NotoSansTamilFontFamily
    } else {
        LoraFontFamily
    }
}

fun titleFontFamilyForText(text: String, languageCode: String? = null): FontFamily {
    val hasTamil = text.any { it in '\u0B80'..'\u0BFF' }
    return if (hasTamil || languageCode.equals("ta", ignoreCase = true)) {
        NotoSansTamilFontFamily
    } else {
        LoraFontFamily
    }
}

fun lyricTextStyle(languageCode: String, fontSizeSp: Float): TextStyle {
    val isTamil = languageCode.equals("ta", ignoreCase = true)
    val lineHeightMultiplier = if (isTamil) 1.62f else 1.52f
    return TextStyle(
        fontFamily = if (isTamil) NotoSansTamilFontFamily else LoraFontFamily,
        fontWeight = FontWeight.Normal,
        fontSize = fontSizeSp.sp,
        lineHeight = (fontSizeSp * lineHeightMultiplier).sp,
        letterSpacing = if (isTamil) 0.1.sp else 0.15.sp
    )
}

